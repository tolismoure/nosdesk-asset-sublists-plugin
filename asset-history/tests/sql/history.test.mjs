test('actual secret transitions and insertions are excluded; upserts preserve the flag', async () => {
  const db = await setup();
  try {
    await db.exec(
      "CREATE UNIQUE INDEX fixture_plugin_data_key ON plugin_data(plugin_id,data_type,key);" +
      "INSERT INTO plugin_data(plugin_id,data_type,key,value,is_secret,workspace_id) " +
      "VALUES(7,'storage','asset-1-category-v1','{\"category\":\"computers\"}',false,1);" +
      // Match the official repository contract: the conflict branch only writes value.
      "INSERT INTO plugin_data(plugin_id,data_type,key,value,is_secret,workspace_id) " +
      "VALUES(7,'storage','asset-1-category-v1','{\"category\":\"computers\"}',true,1) " +
      "ON CONFLICT(plugin_id,data_type,key) DO UPDATE SET value=EXCLUDED.value;"
    );
    const stored = (await db.query("SELECT is_secret FROM plugin_data WHERE plugin_id=7 AND key='asset-1-category-v1'")).rows[0];
    assert.equal(stored.is_secret, false, 'an upsert cannot turn existing storage into a secret');
    const publicHistory = await history(db);
    await db.query("UPDATE plugin_data SET is_secret=true,value=$1::jsonb WHERE plugin_id=7 AND key='asset-1-category-v1'", [JSON.stringify('hidden')]);
    const actualSecret = (await db.query("SELECT is_secret FROM plugin_data WHERE plugin_id=7 AND key='asset-1-category-v1'")).rows[0];
    assert.equal(actualSecret.is_secret, true, 'fixture now contains a real secret');
    const transitionHistory = await history(db);
    assert.equal(transitionHistory.length, publicHistory.length, 'exclude the public-to-secret transition entirely');
    assert(!JSON.stringify(transitionHistory).includes('hidden'));
    await db.exec("DELETE FROM plugin_data WHERE plugin_id=7 AND key='asset-1-category-v1';");
    await db.query("INSERT INTO plugin_data(plugin_id,data_type,key,value,is_secret,workspace_id) VALUES(7,'storage','asset-1-category-v1',$1::jsonb,true,1)", [JSON.stringify('inserted-secret')]);
    const inserted = (await db.query("SELECT is_secret FROM plugin_data WHERE plugin_id=7 AND key='asset-1-category-v1'")).rows[0];
    assert.equal(inserted.is_secret, true);
    const secretHistory = await history(db);
    assert.equal(secretHistory.length, publicHistory.length, 'secret insertion and deletion are also excluded');
    assert(!JSON.stringify(secretHistory).includes('inserted-secret'));
  } finally { await db.close(); }
});
