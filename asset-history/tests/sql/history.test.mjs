import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';

const here = new URL('../../', import.meta.url);
const query = await readFile(new URL('core-extension/backend/src/handlers/asset_history_query.sql', here), 'utf8');
const up = await readFile(new URL('core-extension/backend/migrations/2026-10-13-000000_asset_history/up.sql', here), 'utf8');
const down = await readFile(new URL('core-extension/backend/migrations/2026-10-13-000000_asset_history/down.sql', here), 'utf8');
const upstream = await readFile(new URL('tests/fixtures/upstream-audit-trigger.sql', here), 'utf8');
const childTables = ['asset_loans', 'asset_lifecycle_events', 'asset_usage_log', 'asset_audits', 'asset_media', 'asset_disposals', 'asset_group_assignments', 'asset_directory_memberships', 'ticket_assets'];

// Representative schema; production query/migration and upstream trigger are
// executed unchanged. HTTP/Rust and the complete PG18 schema are separate checks.
async function setup() {
  const db = new PGlite();
  await db.exec(`
    CREATE ROLE nosdesk_app;
    CREATE ROLE nosdesk_admin;
    CREATE TABLE audit_log(id bigint GENERATED BY DEFAULT AS IDENTITY,table_name text,pk_text text,op char(1),before_jsonb jsonb,after_jsonb jsonb,changed_cols text[],actor_uuid uuid,correlation_id uuid,occurred_at timestamptz DEFAULT clock_timestamp(),workspace_id integer NOT NULL DEFAULT nullif(current_setting('app.workspace_id',true),'')::integer,PRIMARY KEY(id,occurred_at)) PARTITION BY RANGE(occurred_at);
    CREATE TABLE audit_log_default PARTITION OF audit_log DEFAULT;
    CREATE TABLE users(uuid uuid PRIMARY KEY,name text);
    CREATE TABLE plugins(id integer PRIMARY KEY,name text,workspace_id integer);
    CREATE TABLE assets(id integer PRIMARY KEY,name text,attributes jsonb,workspace_id integer);
    CREATE TABLE plugin_data(id serial PRIMARY KEY,plugin_id integer,data_type text,key text,value jsonb,is_secret boolean DEFAULT false,workspace_id integer);
  `);
  for (const table of childTables) {
    await db.exec(`CREATE TABLE ${table}(id serial PRIMARY KEY,asset_id integer REFERENCES assets(id) ON DELETE CASCADE,workspace_id integer,notes text);`);
  }
  await db.exec(upstream);
  await db.exec(`CREATE TRIGGER tr_audit_assets AFTER INSERT OR UPDATE OR DELETE ON assets FOR EACH ROW EXECUTE FUNCTION audit_log_trigger('id');
    CREATE TRIGGER tr_audit_plugin_data AFTER INSERT OR UPDATE OR DELETE ON plugin_data FOR EACH ROW EXECUTE FUNCTION audit_log_trigger('id');`);
  await db.exec(up);
  await db.exec(`SET app.workspace_id='1';
    INSERT INTO assets VALUES(1,'PC','{}',1),(2,'PDU','{}',1);
    INSERT INTO plugins VALUES(7,'asset-categories',1),(8,'other-plugin',1);`);
  return db;
}

async function history(db, {ws=1, asset='1', since=null, until=null, time=null, id=null, plugin='7', key='asset-1-category-v1', global=false, limit=201}={}) {
  return (await db.query(query, [ws,asset,since,until,time,id,plugin,key,global,limit])).rows;
}

test('query isolates workspace, asset and secret/cross-plugin storage', async () => {
  const db = await setup();
  try {
    await db.exec(`INSERT INTO plugin_data(plugin_id,data_type,key,value,is_secret,workspace_id) VALUES
      (7,'storage','asset-1-category-v1','{"category":"computers"}',false,1),
      (8,'storage','asset-1-category-v1','{"category":"private"}',false,1),
      (7,'storage','asset-2-category-v1','{}',false,1),
      (7,'storage','asset-1-category-v1','{"sensitive_value":true}',true,1);
      SET app.workspace_id='2';
      INSERT INTO assets VALUES(3,'Other workspace','{}',2);
      INSERT INTO plugin_data(plugin_id,data_type,key,value,is_secret,workspace_id) VALUES(7,'storage','asset-1-category-v1','{"cross_workspace":true}',false,2);`);
    const rows = await history(db);
    assert(rows.length >= 2);
    assert(rows.every(r => r.table_name === 'assets' ? r.pk_text === '1' : r.after_jsonb.plugin_id === 7 && r.after_jsonb.key === 'asset-1-category-v1' && r.after_jsonb.is_secret === false));
    assert(!JSON.stringify(rows).includes('cross_workspace'));
    assert(!JSON.stringify(rows).includes('private'));
    assert(!JSON.stringify(rows).includes('sensitive_value'));
  } finally { await db.close(); }
});

test('new triggers capture related changes and cascade deletion without any viewer', async () => {
  const db = await setup();
  try {
    for (const table of ['asset_disposals','asset_group_assignments','asset_directory_memberships','ticket_assets']) {
      await db.query(`INSERT INTO ${table}(asset_id,workspace_id,notes) VALUES(1,1,'initial')`);
    }
    await db.exec(`UPDATE asset_disposals SET notes='certificate added' WHERE asset_id=1; DELETE FROM assets WHERE id=1;`);
    const rows = await history(db);
    for (const table of ['asset_disposals','asset_group_assignments','asset_directory_memberships','ticket_assets']) {
      assert(rows.some(r => r.table_name === table && r.op === 'I'));
      assert(rows.some(r => r.table_name === table && r.op === 'D' && r.before_jsonb.asset_id === 1));
    }
    assert(rows.some(r => r.table_name === 'assets' && r.op === 'D'));
    const update = rows.find(r => r.table_name === 'asset_disposals' && r.op === 'U');
    assert.equal(update.before_jsonb.notes, 'initial');
    assert.equal(update.after_jsonb.notes, 'certificate added');
  } finally { await db.close(); }
});

test('taxonomy history is opt-in; unchanged asset_id still matches child updates', async () => {
  const db = await setup();
  try {
    await db.exec(`INSERT INTO plugin_data(plugin_id,data_type,key,value,workspace_id) VALUES(7,'storage','taxonomy-v1','{"categories":[]}',1);
      INSERT INTO asset_disposals(asset_id,workspace_id,notes) VALUES(1,1,'old');
      UPDATE asset_disposals SET notes='new' WHERE asset_id=1;`);
    assert(!(await history(db)).some(r => r.table_name === 'plugin_data'));
    assert((await history(db, {global:true})).some(r => r.table_name === 'plugin_data'));
    const row = (await history(db)).find(r => r.table_name === 'asset_disposals' && r.op === 'U');
    assert(row);
    assert(!row.changed_cols.includes('asset_id'));
  } finally { await db.close(); }
});

test('cursor paging is strict and date upper bound exclusive', async () => {
  const db = await setup();
  try {
    await db.exec(`UPDATE assets SET name='A' WHERE id=1; UPDATE assets SET name='B' WHERE id=1;`);
    const all = await history(db);
    const first = await history(db, {limit:2});
    const last = first.at(-1);
    const next = await history(db, {time:last.occurred_at,id:last.id});
    assert.deepEqual([...first,...next].map(r => r.id), all.map(r => r.id));
    assert.equal((await history(db, {until:all.at(-1).occurred_at})).length, 0);
  } finally { await db.close(); }
});

test('migration rollback removes new capture only and retains recorded history', async () => {
  const db = await setup();
  try {
    await db.exec(`INSERT INTO asset_disposals(asset_id,workspace_id,notes) VALUES(1,1,'retained');`);
    const before = (await history(db)).length;
    await db.exec(down);
    assert.equal((await history(db)).length, before);
    const count = await db.query(`SELECT count(*)::int AS total FROM pg_trigger WHERE NOT tgisinternal AND tgname='tr_audit_assets'`);
    assert.equal(count.rows[0].total, 1);
  } finally { await db.close(); }
});

test('historical category labels use the retained state at each assignment', async () => {
  const db = await setup();
  try {
    await db.exec(`INSERT INTO plugin_data(plugin_id,data_type,key,value,workspace_id) VALUES
      (7,'storage','taxonomy-v1','{"categories":[{"id":"c1","name":"Computers","children":[]}]}',1);
      INSERT INTO plugin_data(plugin_id,data_type,key,value,workspace_id) VALUES
      (7,'storage','asset-1-category-v1','{"category":"c1","subcategory":""}',1);
      UPDATE plugin_data SET value='{"categories":[{"id":"c1","name":"Renamed computers","children":[]}]}' WHERE key='taxonomy-v1';
      UPDATE plugin_data SET value='{"category":"c1","subcategory":"sub1"}' WHERE key='asset-1-category-v1';`);
    const assignments = (await history(db)).filter(r => r.table_name === 'plugin_data');
    assert.equal(assignments.length, 2);
    assert.equal(assignments[0].assignment_taxonomy.categories[0].name, 'Renamed computers');
    assert.equal(assignments[1].assignment_taxonomy.categories[0].name, 'Computers');
    await db.exec(`DELETE FROM plugin_data WHERE key='taxonomy-v1';
      UPDATE plugin_data SET value='{"category":"c1","subcategory":""}' WHERE key='asset-1-category-v1';`);
    const latest = (await history(db)).find(r => r.table_name === 'plugin_data');
    assert.equal(latest.assignment_taxonomy, null);
  } finally { await db.close(); }
});

